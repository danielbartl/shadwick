package dev.jbaby.shadwick.examples;

import dev.jbaby.shadwick.Shadwick;
import org.apache.wicket.Page;
import org.apache.wicket.protocol.http.WebApplication;
import org.apache.wicket.request.resource.IResource;
import org.apache.wicket.request.resource.ResourceReference;
import org.apache.wicket.request.resource.ResourceStreamResource;
import org.apache.wicket.util.resource.StringResourceStream;

import java.time.Duration;

/** The showcase's Wicket application, also what the page tests run. */
public class ExamplesApplication extends WebApplication {

    @Override
    public Class<? extends Page> getHomePage() {
        return StudioPage.class;
    }

    @Override
    protected void init() {
        super.init();

        // Browsers request this even without an icon link. Keep it out of the root Studio mapper,
        // whose page construction deliberately normalizes Studio to English/German.
        mountResource("/favicon.ico", new org.apache.wicket.request.resource.PackageResourceReference(BasePage.class, "clover.svg"));

        // Stateless readiness check: do not render a page or allocate a visitor workspace.
        mountResource("/healthz", new ResourceReference(ExamplesApplication.class, "healthz") {
            @Override public IResource getResource() {
                return new ResourceStreamResource(new StringResourceStream("ok", "text/plain"))
                        .setCacheDuration(Duration.ZERO);
            }
        });
        // Keep existing Studio bookmarks working; links generated by Wicket use the root route.
        mount(new StudioPageMapper("/studio"));
        mount(new StudioPageMapper("/"));
        mountPage("/components", HomePage.class);
        for (CatalogPages.Example example : CatalogPages.ALL) mountPage("/" + example.route(), example.page());
        mountPage("/demo-sign-in", UserSignInPage.class);

        // The markup a deployed application sends, also in development mode: Wicket's own
        // tags would be the children of the pages' grid layouts
        getMarkupSettings().setStripWicketTags(true);

        // The skin is vega for every page, unless a visitor picked another one with the
        // skin switcher: kept in the session, so visitors don't change each other's.
        // Wicket's strict, nonce-based Content Security Policy stays as it is.
        Shadwick.install(this)
                .setSkinStore(new SessionSkinStore());
    }
}
