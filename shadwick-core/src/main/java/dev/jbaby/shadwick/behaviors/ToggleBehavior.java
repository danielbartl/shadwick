package dev.jbaby.shadwick.behaviors;

import org.apache.wicket.Component;
import org.apache.wicket.markup.ComponentTag;
import org.apache.wicket.util.value.IValueMap;
import org.apache.wicket.util.value.ValueMap;

import java.util.Objects;

/** Styles a label containing a native checkbox/radio with class sw-toggle-input. */
public class ToggleBehavior extends StyledBehavior {
    public enum Variant {
        DEFAULT(null), OUTLINE("outline");
        private final String value;
        Variant(String value) { this.value = value; }
    }

    public enum Size {
        DEFAULT(null), SMALL("sm"), LARGE("lg");
        private final String value;
        Size(String value) { this.value = value; }
    }

    private Variant variant = Variant.DEFAULT;
    private Size size = Size.DEFAULT;

    public ToggleBehavior() { super("sw-toggle"); }

    public ToggleBehavior setVariant(Variant variant) { this.variant = Objects.requireNonNull(variant); return this; }
    public ToggleBehavior setSize(Size size) { this.size = Objects.requireNonNull(size); return this; }

    @Override
    public void onComponentTag(Component component, ComponentTag tag) {
        super.onComponentTag(component, tag);
        if (variant.value != null) tag.put("data-variant", variant.value); else tag.remove("data-variant");
        if (size.value != null) tag.put("data-size", size.value); else tag.remove("data-size");
    }

    /** Attributes for labels generated by Wicket's native choice components. */
    public IValueMap itemAttributes() {
        IValueMap attributes = new ValueMap();
        attributes.put("class", "sw-toggle sw-toggle-group-item");
        if (variant.value != null) attributes.put("data-variant", variant.value);
        if (size.value != null) attributes.put("data-size", size.value);
        return attributes;
    }
}
